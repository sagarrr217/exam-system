import { config } from '../config/index.js';

export interface GeneratedQuestion {
  text: string;
  type: 'MCQ' | 'TRUE_FALSE';
  marks: number;
  explanation: string;
  options: {
    text: string;
    isCorrect: boolean;
    orderIndex: number;
  }[];
}

export const generateQuestionsWithGemini = async (
  topic: string,
  count: number = 3,
  difficulty: 'easy' | 'medium' | 'hard' = 'medium'
): Promise<GeneratedQuestion[]> => {
  const apiKey = config.gemini.apiKey;
  if (!apiKey) {
    throw new Error('Google Gemini API key is not configured.');
  }

  const prompt = `You are an academic exam question generator.
Generate exactly ${count} distinct multiple-choice questions on the topic: "${topic}".
Difficulty level: ${difficulty}.

Requirements:
1. Each question must be rigorous, clear, and academically sound.
2. Provide exactly 4 plausible options for each question.
3. Designate exactly ONE option as correct (isCorrect: true), and the other three as incorrect (isCorrect: false).
4. Provide a helpful 1-2 sentence academic explanation for the correct answer.
5. Assign a recommended marks value (e.g. 5 or 10 points).
6. Return ONLY a valid JSON array of objects.

Expected JSON schema:
[
  {
    "text": "Question statement here?",
    "type": "MCQ",
    "marks": 10,
    "explanation": "Explanation of why this answer is correct.",
    "options": [
      { "text": "Option A text", "isCorrect": true, "orderIndex": 0 },
      { "text": "Option B text", "isCorrect": false, "orderIndex": 1 },
      { "text": "Option C text", "isCorrect": false, "orderIndex": 2 },
      { "text": "Option D text", "isCorrect": false, "orderIndex": 3 }
    ]
  }
]`;

  const model = 'gemini-3.5-flash-lite';
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.25,
        topP: 0.85
      }
    })
  });

  if (!response.ok) {
    const errorText = await response.text();
    console.error('Gemini API request failed:', response.status, errorText);
    throw new Error(`Gemini API error (${response.status}): ${errorText}`);
  }

  const data = (await response.json()) as any;
  const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text;

  if (!rawText) {
    throw new Error('No question content was generated by Gemini.');
  }

  // Clean code fences or leading text if present
  let cleanedText = rawText.trim();
  const jsonArrayMatch = cleanedText.match(/\[[\s\S]*\]/);
  if (jsonArrayMatch) {
    cleanedText = jsonArrayMatch[0];
  } else {
    cleanedText = cleanedText
      .replace(/^```json\s*/i, '')
      .replace(/^```\s*/i, '')
      .replace(/\s*```$/i, '')
      .trim();
  }

  let questions: any[];
  try {
    questions = JSON.parse(cleanedText);
  } catch (err: any) {
    console.error('Failed to parse Gemini JSON output:', cleanedText);
    // Secondary attempt: clean potential invalid control characters
    try {
      const sanitized = cleanedText.replace(/[\x00-\x1F\x7F-\x9F]/g, '');
      questions = JSON.parse(sanitized);
    } catch {
      throw new Error('Gemini output was not valid JSON.');
    }
  }

  if (!Array.isArray(questions)) {
    throw new Error('Gemini response was not a JSON array of questions.');
  }

  // Normalize questions to match our schema
  return questions.map((q, qIdx) => {
    const options = Array.isArray(q.options)
      ? q.options.map((opt: any, optIdx: number) => ({
          text: String(opt.text || `Option ${optIdx + 1}`),
          isCorrect: Boolean(opt.isCorrect),
          orderIndex: optIdx
        }))
      : [
          { text: 'Option A', isCorrect: true, orderIndex: 0 },
          { text: 'Option B', isCorrect: false, orderIndex: 1 },
          { text: 'Option C', isCorrect: false, orderIndex: 2 },
          { text: 'Option D', isCorrect: false, orderIndex: 3 }
        ];

    // Ensure at least one option is correct
    if (!options.some((o: any) => o.isCorrect)) {
      options[0].isCorrect = true;
    }

    return {
      text: String(q.text || `AI Question ${qIdx + 1} on ${topic}`),
      type: 'MCQ',
      marks: Number(q.marks || 10),
      explanation: String(q.explanation || ''),
      options
    };
  });
};
